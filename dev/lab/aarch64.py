#!/usr/bin/env python3
"""Build the shared kernel lab for Linux AArch64, with pinned Arm references.

The registry includes every public primitive from the host glibc, each Arm
reference variant, and the scalar/NEON configurations and slots of this tree.
It deliberately does not manufacture missing primitives for Arm's library.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shlex
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
PRIMS = ['memcpy', 'memmove', 'memset', 'memcmp', 'strlen', 'strcpy', 'strcat',
         'strcmp', 'strspn', 'strcspn', 'memchr']
SLOTS = PRIMS + ['copy_large', 'fill_large', 'memcmp_large', 'strlen_tail',
                 'strcmp_tail', 'strcpy_long', 'copy_huge', 'fill_huge', 'memchr_large']


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--aor', type=Path, required=True)
    p.add_argument('--libstr', type=Path, required=True)
    p.add_argument('--work', type=Path, required=True)
    p.add_argument('--binary', type=Path, required=True)
    p.add_argument('--cc', default=os.environ.get('CC', 'clang'))
    p.add_argument('--objcopy', default=os.environ.get('OBJCOPY', 'llvm-objcopy'))
    p.add_argument('--nm', default=os.environ.get('NM', 'llvm-nm'))
    p.add_argument('--target', default='aarch64-linux-gnu')
    a = p.parse_args()
    a.work.mkdir(parents=True, exist_ok=True)
    a.binary.parent.mkdir(parents=True, exist_ok=True)
    lock = json.loads((HERE / 'aarch64.lock').read_text())
    for name, expected in lock['sha256'].items():
        if not (a.aor / name).is_file():
            raise SystemExit('aarch64.py: missing Arm reference source %s; set -Daor=/path/to/pinned/checkout' % (a.aor / name))
        if digest(a.aor / name) != expected:
            raise SystemExit('aarch64.py: reference hash mismatch: ' + name)

    def run(cmd, name):
        command = list(map(str, cmd))
        with (a.work / (name + '.log')).open('w') as log:
            log.write(shlex.join(command) + '\n')
            log.flush()
            r = subprocess.run(command, stdout=log, stderr=subprocess.STDOUT)
        if r.returncode:
            raise SystemExit('aarch64.py: %s failed; see %s' % (name, a.work / (name + '.log')))

    def symbols(path):
        text = subprocess.check_output([a.nm, '--defined-only', '-g', str(path)], text=True)
        return sorted({fields[-1] for fields in map(str.split, text.splitlines()) if len(fields) >= 3 and fields[-2] == 'T'})

    cc = shlex.split(a.cc)
    flags = ['--target=' + a.target, *shlex.split(os.environ.get('CPPFLAGS', '')),
             *shlex.split(os.environ.get('CFLAGS', '')), '-O3', '-fPIC', '-fno-builtin',
             '-ffunction-sections', '-falign-functions=64', '-march=armv8-a+simd']
    objs, defs = [], [('glibc', prim, prim, 0) for prim in PRIMS]
    for name in lock['sha256']:
        if not name.endswith('.S'):
            continue
        obj = a.work / (Path(name).stem + '.o')
        prefixed = a.work / ('aor-' + obj.name)
        run([*cc, *flags, '-c', a.aor / name, '-o', obj], obj.stem)
        run([a.objcopy, '--prefix-symbols=aor_', obj, prefixed], 'prefix-' + obj.stem)
        objs.append(prefixed)
        for symbol in symbols(prefixed):
            for prim in PRIMS:
                if symbol.startswith('aor___' + prim + '_'):
                    # Baseline AdvSIMD variants only; no SVE, MOPS or MTE instructions.
                    defs.append(('aor', symbol, prim, 'F_NEON'))
                    break

    slots = []
    for symbol in symbols(a.libstr):
        for suffix in ('scalar', 'neon'):
            for slot in SLOTS:
                if symbol == slot + '_' + suffix:
                    slots.append((slot, symbol, 'F_NEON' if suffix == 'neon' else '0'))
    gen = ['/* generated by dev/lab/aarch64.py */', '#include "str.h"', '#include "dev/lab/kl.h"']
    for i, (_, symbol, _, _) in enumerate(defs):
        gen.append('extern char def_%d[] __asm__("%s");' % (i, symbol))
    for i, (_, symbol, _) in enumerate(slots):
        gen.append('extern char slot_%d[] __asm__("%s");' % (i, symbol))
    gen += ['const KlDef kl_defs[] = {']
    gen += ['    {"%s", "%s", P_%s, def_%d, %s},' % (origin, symbol, prim.upper(), i, need)
            for i, (origin, symbol, prim, need) in enumerate(defs)]
    gen += ['};', 'const unsigned kl_ndefs = %d;' % len(defs), 'const KlSlot kl_slots[] = {']
    gen += ['    {offsetof(struct str_table, %s) / sizeof(void *), "%s", slot_%d, %s, 0},' % (slot, symbol, i, need)
            for i, (slot, symbol, need) in enumerate(slots)]
    gen += ['};', 'const unsigned kl_nslots = %d;' % len(slots),
            'const char *const kl_jcc_configs[] = {0};',
            'const struct str_config *const kl_base_configs = 0;', 'const unsigned kl_base_nconfigs = 0;',
            'struct str_table *const kl_base_table = 0;', 'const char kl_base_rev[] = "";',
            'void *resolved_glibc(void *entry) { return entry; }',
            'const char *glibc_variant(void *entry) {']
    gen += ['    if (entry == (void *)def_%d) return "%s";' % (i, symbol)
            for i, (origin, symbol, _, _) in enumerate(defs) if origin == 'glibc']
    gen += ['    return "unregistered";', '}']
    registry = a.work / 'kernels-gen.c'
    registry.write_text('\n'.join(gen) + '\n')
    for source in (HERE / 'kbench.c', registry):
        obj = a.work / (source.stem + '.o')
        run([*cc, *flags, '-I', ROOT, '-Wall', '-Wextra', '-c', source, '-o', obj], source.stem)
        objs.append(obj)
    # One binary contains both contenders and the unchanged shared benchmark driver.
    run([*cc, *flags, *objs, a.libstr, *shlex.split(os.environ.get('LDFLAGS', '')),
         '-o', a.binary], 'link')
    metadata = {'architecture': a.target, 'reference': lock, 'libstr_sha256': digest(a.libstr),
                'binary_sha256': digest(a.binary), 'reference_primitives': sorted({d[2] for d in defs if d[0] == 'aor'}),
                'definitions': len(defs), 'slots': len(slots),
                'compiler': subprocess.check_output([*cc, '--version'], text=True).splitlines()[0],
                'flags': flags, 'ldflags': shlex.split(os.environ.get('LDFLAGS', ''))}
    (a.work / 'build.json').write_text(json.dumps(metadata, indent=2) + '\n')
    print('AArch64 lab: %d reference kernels, %d slot implementations; %s' % (len(defs), len(slots), a.binary))


if __name__ == '__main__':
    main()
